def color_label_to_class_index(label: np.ndarray) -> np.ndarray:
    """Map an RGB color-label image to a per-pixel class-index map.

    BDD100k stores masks as RGB PNGs matching ``CLASS_COLORS``. Semantic
    segmentation loss functions and metrics require 2D class index maps
    rather than RGB triples, so each pixel is mapped to its palette row index.

    Steps
    -----
    1. Initialize output array with the fallback ID for the ``Unknown`` class.
    2. Vectorially match each RGB triple in ``CLASS_COLORS`` and assign the class ID.

    Parameters
    ----------
    label : np.ndarray
        RGB color-label array of shape ``(H, W, 3)``.

    Returns
    -------
    np.ndarray
        Class-index array of shape ``(H, W)`` with values in ``[0, NUM_CLASSES)``.
    """
    class_ids = np.full(label.shape[:2], Configuration.IGNORED_CLASS, dtype=np.uint8)
    for class_id, (red, green, blue) in enumerate(CLASS_COLORS):
        match = (
            (label[..., 0] == red)
            & (label[..., 1] == green)
            & (label[..., 2] == blue)
        )
        class_ids[match] = class_id
    return class_ids


def find_image_path_from_mask(complete_mask_path: str, base_image_path: str) -> str:
    """Derive the corresponding JPEG image path from a mask PNG path.

    Steps
    -----
    1. Extract the image ID by stripping the mask-specific suffix.
    2. Construct and return the full path in the target image folder.

    Parameters
    ----------
    complete_mask_path : str
        Full filesystem path to a segmentation mask PNG.
    base_image_path : str
        Directory containing the corresponding JPEG images.

    Returns
    -------
    str
        Full filesystem path to the matching image file.
    """
    file_path_split = complete_mask_path.split("/")
    mask_file_name = file_path_split[-1].split("_")[0]
    return base_image_path + "/" + mask_file_name + ".jpg"


def find_train_image_path_from_mask(complete_mask_path: str) -> str:
    """Locate the training image corresponding to a training mask.

    Steps
    -----
    1. Delegate to ``find_image_path_from_mask`` using ``ImagePath.IMAGE_TRAIN_PATH``.

    Parameters
    ----------
    complete_mask_path : str
        Full path to a training mask PNG.

    Returns
    -------
    str
        Full path to the corresponding training image JPEG.
    """
    return find_image_path_from_mask(complete_mask_path, ImagePath.IMAGE_TRAIN_PATH)


def find_mask_path_from_image(complete_image_path: str, base_mask_path: str) -> str:
    """Derive the corresponding PNG mask path from a JPEG image path.

    Steps
    -----
    1. Extract the sample stem by stripping the ``.jpg`` extension.
    2. Append the ``_train_color.png`` suffix used by BDD100k masks.

    Parameters
    ----------
    complete_image_path : str
        Full filesystem path to an image JPEG.
    base_mask_path : str
        Directory containing the corresponding mask PNGs.

    Returns
    -------
    str
        Full filesystem path to the matching mask file.
    """
    file_path_split = complete_image_path.split("/")
    mask_file_name = file_path_split[-1].split(".")[0]
    return base_mask_path + "/" + mask_file_name + "_train_color.png"


def load_dataset_from_files() -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Scan disk and load the BDD100k train, validation, and test splits.

    This function duplicates the exact partitioning logic from the training scripts
    so the evaluation evaluates the model on the identical test split.

    Steps
    -----
    1. Collect train masks and filter out corrupted or non-standard resolutions.
    2. Map to corresponding train images and filter any missing or malformed pairs.
    3. Partition the train-test pool using 80/20 train_test_split with fixed SEED.
    4. Collect and validate validation masks and images.
    5. Return DataFrames for train, validation, and test splits.

    Returns
    -------
    Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]
        DataFrames representing ``(train_df, val_df, test_df)``.
    """
    # Build the valid training pool without mutating a list during iteration.
    # Preserving candidate order matters because the seeded train/test split is
    # deterministic only when it receives the same ordered population.
    train_mask_candidates = glob.glob(
        f"{ImagePath.SEGMENTATION_MASK_TRAIN_PATH}/*.png"
    )
    train_mask_paths: List[str] = []
    problematic_masks: List[str] = []
    for complete_mask_path in train_mask_candidates:
        with Image.open(complete_mask_path) as img:
            width, height = img.size
            if width != 1280 or height != 720:
                problematic_masks.append(complete_mask_path)
                continue
        train_mask_paths.append(complete_mask_path)

    train_image_paths: List[str] = []
    validated_train_mask_paths: List[str] = []
    problematic_images: List[str] = []
    for complete_mask_path in train_mask_paths:
        complete_image_path = find_train_image_path_from_mask(complete_mask_path)
        with Image.open(complete_image_path) as img:
            width, height = img.size
            if width != 1280 or height != 720:
                problematic_images.append(complete_image_path)
                continue
        train_image_paths.append(complete_image_path)
        validated_train_mask_paths.append(complete_mask_path)

    train_test_df = pd.DataFrame({
        "image_paths": train_image_paths,
        "mask_paths": validated_train_mask_paths,
    })
    train_df, test_df = train_test_split(
        train_test_df, test_size=0.2, random_state=Configuration.SEED
    )

    val_mask_paths = glob.glob(f"{ImagePath.SEGMENTATION_MASK_VAL_PATH}/*.png")
    for complete_mask_path in val_mask_paths:
        with Image.open(complete_mask_path) as img:
            width, height = img.size
            if width != 1280 or height != 720:
                val_mask_paths.remove(complete_mask_path)

    val_image_paths = list(map(find_image_path_from_mask, val_mask_paths, [ImagePath.IMAGE_VAL_PATH] * len(val_mask_paths)))
    for complete_image_path in val_image_paths:
        with Image.open(complete_image_path) as img:
            width, height = img.size
            if width != 1280 or height != 720:
                val_image_paths.remove(complete_image_path)
                val_mask_paths.remove(find_mask_path_from_image(complete_image_path, ImagePath.SEGMENTATION_MASK_VAL_PATH))

    val_df = pd.DataFrame({
        "image_paths": val_image_paths,
        "mask_paths": val_mask_paths,
    })

    return train_df, val_df, test_df


class BDDSegmentationDataset(Dataset[Tuple[ImageTensor, MaskTensor]]):
    """BDD100k semantic segmentation dataset loader.

    Parameters
    ----------
    df : pd.DataFrame
        DataFrame containing ``image_paths`` and ``mask_paths`` columns.
    transform : Optional[A.Compose], optional
        Albumentations transform pipeline applied to image and mask. Defaults to None.
    """

    def __init__(self, df: pd.DataFrame, transform: Optional[A.Compose] = None) -> None:
        super().__init__()
        self.image_paths: List[str] = df["image_paths"].to_list()
        self.mask_paths: List[str] = df["mask_paths"].to_list()
        self.transform = transform

    @jaxtyped(typechecker=beartype)
    def load_sample(self, index: int) -> Tuple[NumpyImage, ClassIndexArray]:
        """Load an image and its class-index mask from disk.

        Steps
        -----
        1. Open image and mask PNGs as RGB arrays.
        2. Normalize image pixel intensities to [0, 1].
        3. Convert RGB color-label mask to per-pixel class index array.

        Parameters
        ----------
        index : int
            Index of the sample to load.

        Returns
        -------
        Tuple[NumpyImage, ClassIndexArray]
            Normalized image array and per-pixel uint8 class index map.

        Raises
        ------
        IndexError
            If ``index`` is out of bounds for the dataset path lists.
        """
        image_path = self.image_paths[index]
        mask_path = self.mask_paths[index]

        image_pil = Image.open(image_path).convert("RGB")
        mask_pil = Image.open(mask_path).convert("RGB")

        image = np.array(image_pil).astype(np.float32) / 255.0
        class_mask = color_label_to_class_index(np.array(mask_pil))

        return image, class_mask

    def __len__(self) -> int:
        """Return the total number of samples in the dataset."""
        return len(self.image_paths)

    @jaxtyped(typechecker=beartype)
    def __getitem__(self, index: int) -> Tuple[ImageTensor, MaskTensor]:
        """Retrieve transformed image and one-hot mask tensors at index.

        Steps
        -----
        1. Load raw sample via ``load_sample``.
        2. Apply resize and PyTorch transposition transforms.
        3. One-hot encode mask into ``(NUM_CLASSES, H, W)`` float tensor.

        Parameters
        ----------
        index : int
            Index of the sample to retrieve.

        Returns
        -------
        Tuple[ImageTensor, MaskTensor]
            Pair of transformed image ``(3, H, W)`` and one-hot mask ``(20, H, W)``.
        """
        image, class_mask = self.load_sample(index)

        if self.transform:
            transformed = self.transform(image=image, mask=class_mask)
        else:
            transformed = ToTensorV2()(image=image, mask=class_mask)

        # One-hot encode so the channel dimension aligns with the model's logits
        mask_one_hot = torch.nn.functional.one_hot(
            transformed["mask"].to(torch.int64), Configuration.NUM_CLASSES
        ).permute(2, 0, 1).float()

        return transformed["image"], mask_one_hot


@jaxtyped(typechecker=beartype)
def forward(model: nn.Module, x: BatchImage) -> Logits:
    """Execute model forward pass and verify batch tensor shape contract.

    Parameters
    ----------
    model : nn.Module
        Trained semantic segmentation model.
    x : BatchImage
        Batch of images of shape ``(B, 3, H, W)``.

    Returns
    -------
    Logits
        Raw output logits of shape ``(B, NUM_CLASSES, H, W)``.
    """
    return cast(Logits, model(x))


@torch.no_grad()
def compute_batch_macro_iou(
    y_pred: torch.Tensor,
    y_true: torch.Tensor,
    num_classes: int = 19,
    eps: float = 1e-7,
) -> float:
    """Compute per-batch macro IoU over non-empty classes.

    Steps
    -----
    1. Collapse predictions and targets to 2D class maps using argmax.
    2. Evaluate intersection and union class-by-class for classes 0 to ``num_classes - 1``.
    3. Average IoU strictly over classes that appear in either ground-truth or prediction.

    Parameters
    ----------
    y_pred : torch.Tensor
        Model output logits of shape ``(B, C, H, W)``.
    y_true : torch.Tensor
        One-hot ground-truth masks of shape ``(B, C, H, W)``.
    num_classes : int, optional
        Number of valid classes to consider. Defaults to 19.
    eps : float, optional
        Smoothing constant to prevent division by zero. Defaults to 1e-7.

    Returns
    -------
    float
        Macro IoU score averaged across present classes in the batch.
    """
    preds = y_pred.argmax(dim=1)
    targets = y_true.argmax(dim=1)

    iou_per_class: List[float] = []
    for cls in range(num_classes):
        pred_mask = preds == cls
        true_mask = targets == cls

        intersection = (pred_mask & true_mask).sum().float().item()
        union = (pred_mask | true_mask).sum().float().item()

        if union > 0:
            iou_per_class.append((intersection + eps) / (union + eps))

    return float(np.mean(iou_per_class)) if iou_per_class else 0.0


def colorize_mask(class_mask: np.ndarray, palette: np.ndarray) -> np.ndarray:
    """Map a 2D class-index array to an RGB image using the specified color palette.

    Steps
    -----
    1. Cast the class index array to integer indices.
    2. Index rows of ``palette`` to obtain an RGB representation.

    Parameters
    ----------
    class_mask : np.ndarray
        Array of shape ``(H, W)`` containing integer class indices.
    palette : np.ndarray
        Array of shape ``(NUM_CLASSES, 3)`` mapping class ID to RGB color.

    Returns
    -------
    np.ndarray
        RGB image of shape ``(H, W, 3)`` and dtype matching ``palette``.
    """
    return palette[class_mask.astype(np.int64)]


def load_trained_model(model_path: str, device: torch.device) -> nn.Module:
    """Load a trained segmentation model checkpoint from disk.

    Steps
    -----
    1. Resolve and verify checkpoint path existence.
    2. Load model using ``torch.load`` with ``weights_only=False`` to unpack
       serialized ``nn.Module`` objects produced by ``train_teacher.py``/``train_student.py``.
    3. Transfer model to target ``device`` and switch into ``eval()`` mode.
    4. Freeze all model parameters to prevent weight updates during adversarial attacks.

    Parameters
    ----------
    model_path : str
        Filesystem path to the model ``.pt`` file.
    device : torch.device
        Device (CUDA or CPU) on which to place the model.

    Returns
    -------
    nn.Module
        Loaded, frozen PyTorch segmentation model ready for evaluation.

    Raises
    ------
    FileNotFoundError
        If ``model_path`` does not exist.
    TypeError
        If the loaded checkpoint object is not an ``nn.Module``.
    """
    # weights_only=False is required because the project saves entire nn.Module objects
    checkpoint = torch.load(model_path, map_location=device, weights_only=False)

    if not isinstance(checkpoint, nn.Module):
        raise TypeError(
            f"Checkpoint at '{model_path}' loaded an object of type {type(checkpoint)}, "
            "but an nn.Module instance was expected."
        )

    model = checkpoint.to(device)
    model.eval()

    # Freeze model weights so autograd does not allocate parameter gradient memory
    for param in model.parameters():
        param.requires_grad = False

    return model


@jaxtyped(typechecker=beartype)
def pgd_attack(
    model: nn.Module,
    images: BatchImage,
    targets: BatchMask,
    loss_fn: Optional[nn.Module] = None,
    epsilon: float = 0.03,
    alpha: float = 0.01,
    num_steps: int = 10,
    random_start: bool = False,
) -> BatchImage:
    """Generate untargeted adversarial perturbations using Projected Gradient Descent (PGD).

    PGD iteratively maximizes the segmentation loss with respect to the input image
    within an L-infinity ball of radius ``epsilon``. For untargeted attacks, maximizing
    cross-entropy loss pushes predictions away from the ground-truth annotations.

    Steps
    -----
    1. Freeze model in eval mode and prepare target class index map.
    2. Initialize perturbed input, optionally adding uniform random noise in [-epsilon, epsilon].
    3. For ``num_steps`` iterations:
       a. Track gradients on the current perturbed image.
       b. Compute model logits and evaluate segmentation loss.
       c. Compute input gradient via autograd and step in the direction of the sign.
       d. Project perturbation back onto the L-infinity epsilon ball.
       e. Clamp the resulting adversarial image to the valid [0, 1] range.
    4. Return the crafted adversarial image batch.

    Parameters
    ----------
    model : nn.Module
        Trained segmentation model being attacked.
    images : BatchImage
        Batch of clean images with shape ``(B, 3, H, W)`` and values in ``[0, 1]``.
    targets : BatchMask
        One-hot ground-truth masks of shape ``(B, NUM_CLASSES, H, W)``.
    loss_fn : Optional[nn.Module], optional
        Differentiable loss function to maximize. Defaults to
        ``nn.CrossEntropyLoss(ignore_index=19)`` so unannotated pixels do not
        corrupt adversarial gradients.
    epsilon : float, optional
        Maximum L-infinity perturbation radius. Defaults to 0.03.
    alpha : float, optional
        Step size per iteration. Defaults to 0.01.
    num_steps : int, optional
        Number of attack iterations. Defaults to 10.
    random_start : bool, optional
        Whether to initialize with random uniform perturbation. Defaults to False.

    Returns
    -------
    BatchImage
        Adversarial image batch of shape ``(B, 3, H, W)``.
    """
    model.eval()

    # Ignore class 19 (Unknown) so background noise does not misguide the attack
    if loss_fn is None:
        effective_loss: nn.Module = nn.CrossEntropyLoss(ignore_index=Configuration.IGNORED_CLASS)
    else:
        effective_loss = loss_fn

    # Collapse one-hot targets to class indices for standard cross-entropy evaluation
    target_indices = targets.argmax(dim=1).to(torch.int64)

    # Initialize perturbation
    if random_start:
        noise = torch.empty_like(images).uniform_(-epsilon, epsilon)
        x_adv = torch.clamp(images + noise, 0.0, 1.0).detach()
    else:
        x_adv = images.clone().detach()

    # Multi-step projected gradient ascent
    for _ in range(num_steps):
        # Enable autograd on input tensor to compute dLoss/dx_adv
        x_adv = x_adv.clone().detach().requires_grad_(True)

        adv_logits = forward(model, x_adv)
        loss = effective_loss(adv_logits, target_indices)

        # Compute gradient with respect to perturbed input
        grad = torch.autograd.grad(loss, x_adv, retain_graph=False, create_graph=False)[0]

        # Step along gradient sign (gradient ascent), project onto L_inf ball, and clamp to [0, 1]
        perturbation = x_adv.detach() + alpha * grad.sign() - images
        perturbation = torch.clamp(perturbation, -epsilon, epsilon)
        x_adv = torch.clamp(images + perturbation, 0.0, 1.0).detach()

    return x_adv


def evaluate_robustness(
    model: nn.Module,
    dataloader: DataLoader[Tuple[ImageTensor, MaskTensor]],
    device: torch.device,
    epsilon: float = 0.03,
    alpha: float = 0.01,
    num_steps: int = 10,
    num_classes: int = 19,
    ignore_index: int = -1,
    ignored_class: int = 19,
) -> Dict[str, Union[float, List[float]]]:
    """Run full clean and 10-step PGD adversarial evaluation on a dataloader.

    Confusion counts (TP, FP, FN, TN) are accumulated over the entire test set
    before reduction, guaranteeing statistically robust metrics regardless of
    batch-level class imbalances.

    Steps
    -----
    1. Iterate through dataloader batches.
    2. Run clean forward pass under ``torch.no_grad`` to obtain clean logits.
    3. Generate 10-step PGD adversarial images using ``pgd_attack``.
    4. Run adversarial forward pass under ``torch.no_grad`` to obtain perturbed logits.
    5. Accumulate per-class confusion statistics for both clean and adversarial outputs.
    6. Compute dataset-wide macro IoU, pixel accuracy, Dice score, and per-class IoU.

    Parameters
    ----------
    model : nn.Module
        Trained model being evaluated.
    dataloader : DataLoader[Tuple[ImageTensor, MaskTensor]]
        DataLoader delivering evaluation batches.
    device : torch.device
        Hardware device for computation.
    epsilon : float, optional
        L-infinity perturbation bound. Defaults to 0.03.
    alpha : float, optional
        Step size per iteration. Defaults to 0.01.
    num_steps : int, optional
        Number of PGD iterations. Defaults to 10.
    num_classes : int, optional
        Number of valid segmentation classes (excluding Unknown). Defaults to 19.
    ignore_index : int, optional
        Sentinel index for ignored pixels in ``smp.metrics.get_stats``. Defaults to -1.
    ignored_class : int, optional
        Class index corresponding to Unknown in dataset. Defaults to 19.

    Returns
    -------
    Dict[str, Union[float, List[float]]]
        Dictionary with clean/adversarial metrics and untargeted ASR.

    Raises
    ------
    ValueError
        If the dataloader produces zero batches.
    """
    model.eval()

    clean_tp_total: Optional[torch.Tensor] = None
    clean_fp_total: Optional[torch.Tensor] = None
    clean_fn_total: Optional[torch.Tensor] = None
    clean_tn_total: Optional[torch.Tensor] = None

    adv_tp_total: Optional[torch.Tensor] = None
    adv_fp_total: Optional[torch.Tensor] = None
    adv_fn_total: Optional[torch.Tensor] = None
    adv_tn_total: Optional[torch.Tensor] = None

    clean_batch_iou_sum = 0.0
    adv_batch_iou_sum = 0.0

    for X, y in tqdm(dataloader, desc="Evaluating robustness"):
        X, y = X.to(device), y.to(device)

        # 1. Clean forward pass (no gradients needed)
        with torch.no_grad():
            clean_logits = forward(model, X)
            clean_preds = clean_logits.argmax(dim=1)

        # 2. Craft 10-step PGD adversarial examples
        adv_X = pgd_attack(
            model=model,
            images=X,
            targets=y,
            epsilon=epsilon,
            alpha=alpha,
            num_steps=num_steps,
        )

        # 3. Adversarial forward pass
        with torch.no_grad():
            adv_logits = forward(model, adv_X)
            adv_preds = adv_logits.argmax(dim=1)

        # 4. Relabel Unknown class (19) to sentinel -1 so smp excludes it from metrics
        targets = y.argmax(dim=1)
        target_relabelled = torch.where(
            targets == ignored_class, torch.full_like(targets, ignore_index), targets
        )
        clean_preds_relabelled = torch.where(
            clean_preds == ignored_class, torch.full_like(clean_preds, ignore_index), clean_preds
        )
        adv_preds_relabelled = torch.where(
            adv_preds == ignored_class, torch.full_like(adv_preds, ignore_index), adv_preds
        )

        # 5. Accumulate clean confusion counts
        c_tp, c_fp, c_fn, c_tn = smp.metrics.functional.get_stats(
            clean_preds_relabelled,
            target_relabelled,
            mode="multiclass",
            ignore_index=ignore_index,
            num_classes=num_classes,
        )
        clean_tp_total = c_tp.sum(dim=0) if clean_tp_total is None else clean_tp_total + c_tp.sum(dim=0)
        clean_fp_total = c_fp.sum(dim=0) if clean_fp_total is None else clean_fp_total + c_fp.sum(dim=0)
        clean_fn_total = c_fn.sum(dim=0) if clean_fn_total is None else clean_fn_total + c_fn.sum(dim=0)
        clean_tn_total = c_tn.sum(dim=0) if clean_tn_total is None else clean_tn_total + c_tn.sum(dim=0)

        # 6. Accumulate adversarial confusion counts
        a_tp, a_fp, a_fn, a_tn = smp.metrics.functional.get_stats(
            adv_preds_relabelled,
            target_relabelled,
            mode="multiclass",
            ignore_index=ignore_index,
            num_classes=num_classes,
        )
        adv_tp_total = a_tp.sum(dim=0) if adv_tp_total is None else adv_tp_total + a_tp.sum(dim=0)
        adv_fp_total = a_fp.sum(dim=0) if adv_fp_total is None else adv_fp_total + a_fp.sum(dim=0)
        adv_fn_total = a_fn.sum(dim=0) if adv_fn_total is None else adv_fn_total + a_fn.sum(dim=0)
        adv_tn_total = a_tn.sum(dim=0) if adv_tn_total is None else adv_tn_total + a_tn.sum(dim=0)

        # Per-batch macro IoU tracking
        clean_batch_iou_sum += compute_batch_macro_iou(clean_logits, y, num_classes=num_classes)
        adv_batch_iou_sum += compute_batch_macro_iou(adv_logits, y, num_classes=num_classes)

    if clean_tp_total is None or adv_tp_total is None:
        raise ValueError("The evaluation dataloader yielded zero batches.")

    # Macro mean IoU across the whole dataset (primary metric for ASR)
    clean_mean_iou = float(smp.metrics.iou_score(clean_tp_total, clean_fp_total, clean_fn_total, clean_tn_total, reduction="macro").item())
    adv_mean_iou = float(smp.metrics.iou_score(adv_tp_total, adv_fp_total, adv_fn_total, adv_tn_total, reduction="macro").item())

    # Class-wise IoUs
    clean_class_iou = cast(List[float], smp.metrics.iou_score(clean_tp_total, clean_fp_total, clean_fn_total, clean_tn_total, reduction=None).tolist())
    adv_class_iou = cast(List[float], smp.metrics.iou_score(adv_tp_total, adv_fp_total, adv_fn_total, adv_tn_total, reduction=None).tolist())

    # Pixel accuracy and Dice (F1) scores
    clean_pixel_acc = float(smp.metrics.recall(clean_tp_total, clean_fp_total, clean_fn_total, clean_tn_total, reduction="micro").item())
    adv_pixel_acc = float(smp.metrics.recall(adv_tp_total, adv_fp_total, adv_fn_total, adv_tn_total, reduction="micro").item())
    clean_dice = float(smp.metrics.f1_score(clean_tp_total, clean_fp_total, clean_fn_total, clean_tn_total, reduction="macro").item())
    adv_dice = float(smp.metrics.f1_score(adv_tp_total, adv_fp_total, adv_fn_total, adv_tn_total, reduction="macro").item())

    num_batches = len(dataloader)
    return {
        "clean_mean_iou": clean_mean_iou,
        "adv_mean_iou": adv_mean_iou,
        "clean_pixel_accuracy": clean_pixel_acc,
        "adv_pixel_accuracy": adv_pixel_acc,
        "clean_dice": clean_dice,
        "adv_dice": adv_dice,
        "clean_class_iou": clean_class_iou,
        "adv_class_iou": adv_class_iou,
        "clean_batch_macro_iou": clean_batch_iou_sum / num_batches,
        "adv_batch_macro_iou": adv_batch_iou_sum / num_batches,
    }


def visualize_adversarial_predictions(
    model: nn.Module,
    test_df: pd.DataFrame,
    device: torch.device,
    epsilon: float = 0.03,
    alpha: float = 0.01,
    num_steps: int = 10,
    num_samples: int = 4,
    output_path: str = "./model/adversarial_predictions.png",
) -> None:
    """Render a visual side-by-side comparison of clean and adversarial predictions.

    Steps
    -----
    1. Sample random test rows using the fixed seed.
    2. Craft adversarial examples for each sample.
    3. Generate colorized prediction maps for clean and adversarial inputs.
    4. Export comparison grid (Image / Ground Truth / Clean Pred / Adv Pred / Perturbation).

    Parameters
    ----------
    model : nn.Module
        Trained segmentation model.
    test_df : pd.DataFrame
        DataFrame of test samples.
    device : torch.device
        Hardware device for inference.
    epsilon : float, optional
        L-infinity perturbation bound. Defaults to 0.03.
    alpha : float, optional
        Step size per iteration. Defaults to 0.01.
    num_steps : int, optional
        Number of PGD iterations. Defaults to 10.
    num_samples : int, optional
        Number of samples to visualize. Defaults to 4.
    output_path : str, optional
        Destination image path.

    Raises
    ------
    ValueError
        If ``test_df`` is empty.
    """
    if test_df.empty:
        raise ValueError("test_df contains no rows to visualize.")

    sample_df = test_df.sample(
        n=min(num_samples, len(test_df)),
        random_state=Configuration.SEED,
    ).reset_index(drop=True)

    num_rows = len(sample_df)
    fig, axes = plt.subplots(num_rows, 5, figsize=(25, 5 * num_rows))
    if num_rows == 1:
        axes = axes[np.newaxis, :]

    sample_ds = BDDSegmentationDataset(sample_df)
    model.eval()

    for row in range(num_rows):
        image, class_mask = sample_ds.load_sample(row)

        image_tensor = torch.from_numpy(image.transpose(2, 0, 1)).contiguous().unsqueeze(0).to(device)
        mask_tensor = torch.nn.functional.one_hot(
            torch.from_numpy(class_mask).to(torch.int64), Configuration.NUM_CLASSES
        ).permute(2, 0, 1).float().unsqueeze(0).to(device)

        # Clean inference
        with torch.no_grad():
            clean_logits = model(image_tensor)
        clean_pred_class = clean_logits.argmax(dim=1).squeeze(0).cpu().numpy()

        # Adversarial attack and inference
        adv_image_tensor = pgd_attack(
            model=model,
            images=image_tensor,
            targets=mask_tensor,
            epsilon=epsilon,
            alpha=alpha,
            num_steps=num_steps,
        )
        with torch.no_grad():
            adv_logits = model(adv_image_tensor)
        adv_pred_class = adv_logits.argmax(dim=1).squeeze(0).cpu().numpy()

        # Colorize masks
        clean_pred_color = colorize_mask(clean_pred_class, CLASS_COLORS).astype(np.float32) / 255.0
        adv_pred_color = colorize_mask(adv_pred_class, CLASS_COLORS).astype(np.float32) / 255.0
        true_mask_color = colorize_mask(class_mask, CLASS_COLORS).astype(np.float32) / 255.0

        # Amplified perturbation map for visual inspection
        diff = np.abs(adv_image_tensor.squeeze(0).permute(1, 2, 0).cpu().numpy() - image)
        diff_vis = np.clip(diff * 10.0, 0.0, 1.0)

        # Plot columns
        axes[row, 0].imshow(image)
        axes[row, 0].set_title("Original Clean Image")

        axes[row, 1].imshow(image)
        axes[row, 1].imshow(true_mask_color, alpha=0.5)
        axes[row, 1].set_title("Ground Truth Mask")

        axes[row, 2].imshow(image)
        axes[row, 2].imshow(clean_pred_color, alpha=0.5)
        axes[row, 2].set_title("Clean Model Prediction")

        axes[row, 3].imshow(image)
        axes[row, 3].imshow(adv_pred_color, alpha=0.5)
        axes[row, 3].set_title("Adversarial Prediction (10-step PGD)")

        axes[row, 4].imshow(diff_vis)
        axes[row, 4].set_title("Perturbation (Amplified 10x)")

        for ax in axes[row]:
            ax.set_xticks([])
            ax.set_yticks([])

    fig.tight_layout()
    fig.savefig(output_path, dpi=150)
    plt.close(fig)


def load_pair_specification(pair_csv_path: str) -> pd.DataFrame:
    """Load and validate the requested weather/time-of-day pair specification.

    The ``count`` column is the expected number of samples in the evaluator's
    held-out segmentation subset after joining to the 10K/100K metadata
    intersection and removing undefined environment labels. It must therefore
    equal the number of samples actually evaluated for each pair.

    Steps
    -----
    1. Read the CSV and discard any exported unnamed index column.
    2. Require ``weather``, ``time_of_day``, and ``count`` columns.
    3. Normalize surrounding whitespace and validate unique, non-negative counts.

    Parameters
    ----------
    pair_csv_path : str
        Path to the weather/time-of-day pair CSV.

    Returns
    -------
    pd.DataFrame
        Validated pair table with ``weather``, ``time_of_day``, and ``count``.

    Raises
    ------
    FileNotFoundError
        If ``pair_csv_path`` does not exist.
    ValueError
        If required columns or valid pair/count values are missing.
    """
    # Validate the specification before doing model work so bad inputs fail early.
    if not os.path.isfile(pair_csv_path):
        raise FileNotFoundError(f"Pair CSV not found: {pair_csv_path}")

    pair_df = pd.read_csv(pair_csv_path)
    pair_df = pair_df.loc[:, ~pair_df.columns.astype(str).str.startswith("Unnamed:")].copy()

    required_columns = {"weather", "time_of_day", "count"}
    missing_columns = required_columns.difference(pair_df.columns)
    if missing_columns:
        raise ValueError(
            "Pair CSV is missing required columns: "
            + ", ".join(sorted(missing_columns))
        )

    pair_df = pair_df[["weather", "time_of_day", "count"]].copy()
    if pair_df[["weather", "time_of_day"]].isna().any().any():
        raise ValueError("Pair CSV contains missing weather or time_of_day values.")

    # Keep category spelling intact and strip only accidental surrounding whitespace.
    pair_df["weather"] = pair_df["weather"].astype(str).str.strip()
    pair_df["time_of_day"] = pair_df["time_of_day"].astype(str).str.strip()
    if (pair_df["weather"] == "").any() or (pair_df["time_of_day"] == "").any():
        raise ValueError("Pair CSV contains an empty weather or time_of_day value.")

    numeric_counts = pd.to_numeric(pair_df["count"], errors="raise")
    if ((numeric_counts % 1) != 0).any() or (numeric_counts < 0).any():
        raise ValueError("Pair CSV counts must be non-negative integers.")
    pair_df["count"] = numeric_counts.astype(int)

    duplicate_pairs = pair_df.duplicated(subset=["weather", "time_of_day"], keep=False)
    if duplicate_pairs.any():
        duplicates = pair_df.loc[duplicate_pairs, ["weather", "time_of_day"]]
        raise ValueError(
            "Pair CSV contains duplicate weather/time_of_day rows: "
            f"{duplicates.to_dict(orient='records')}"
        )

    return pair_df


def load_intersection_metadata(intersection_csv_path: str) -> pd.DataFrame:
    """Load and validate the 10K/100K image-metadata intersection CSV.

    The CSV is expected to use the schema emitted by
    ``find_100k_10k_intersection.py``. Only fields needed for pair-wise
    evaluation are retained after validation.

    Steps
    -----
    1. Read the intersection CSV and require the image ID, environment labels,
       label/image split metadata, same-split flag, and image path.
    2. Normalize string fields and reject missing or duplicate image IDs.
    3. Verify every ``image_path`` basename matches its declared ``id``.
    4. Rename ``timeofday`` to ``time_of_day`` for alignment with the pair CSV.

    Parameters
    ----------
    intersection_csv_path : str
        Path to ``bdd100k_10k_images_with_100k_metadata_intersection.csv``.

    Returns
    -------
    pd.DataFrame
        Validated table with ``id``, ``weather``, ``time_of_day``, split
        metadata, and ``metadata_image_path`` columns.

    Raises
    ------
    FileNotFoundError
        If ``intersection_csv_path`` does not exist.
    ValueError
        If required columns are missing, values are empty, IDs are duplicated,
        or an image path does not match its declared ID.
    """
    # This CSV is the image-level source of truth for environment metadata, so
    # validate it before reconstructing any evaluation subset.
    if not os.path.isfile(intersection_csv_path):
        raise FileNotFoundError(
            f"Intersection CSV not found: {intersection_csv_path}"
        )

    intersection_df = pd.read_csv(intersection_csv_path, dtype=str)
    required_columns = {
        "id",
        "weather",
        "timeofday",
        "label_split",
        "image_split",
        "same_split",
        "image_path",
    }
    missing_columns = required_columns.difference(intersection_df.columns)
    if missing_columns:
        raise ValueError(
            "Intersection CSV is missing required columns: "
            + ", ".join(sorted(missing_columns))
        )

    intersection_df = intersection_df[
        [
            "id",
            "weather",
            "timeofday",
            "label_split",
            "image_split",
            "same_split",
            "image_path",
        ]
    ].copy()
    if intersection_df.isna().any().any():
        raise ValueError(
            "Intersection CSV contains missing values in required columns."
        )

    # Preserve category spelling exactly while removing accidental surrounding
    # whitespace introduced by manual CSV editing.
    for column in [
        "id",
        "weather",
        "timeofday",
        "label_split",
        "image_split",
        "same_split",
        "image_path",
    ]:
        intersection_df[column] = intersection_df[column].str.strip()
        if (intersection_df[column] == "").any():
            raise ValueError(
                f"Intersection CSV contains an empty value in column '{column}'."
            )

    duplicate_ids = intersection_df["id"].duplicated(keep=False)
    if duplicate_ids.any():
        duplicate_examples = (
            intersection_df.loc[duplicate_ids, "id"].drop_duplicates().head(10).tolist()
        )
        raise ValueError(
            "Intersection CSV contains duplicate image IDs, e.g. "
            f"{duplicate_examples}"
        )

    # The producer writes the same BDD image ID into both ``id`` and the JPG
    # basename. Checking that invariant catches stale or manually mixed rows.
    path_ids = intersection_df["image_path"].map(
        lambda image_path: os.path.splitext(os.path.basename(image_path))[0]
    )
    mismatch_mask = path_ids != intersection_df["id"]
    if mismatch_mask.any():
        mismatch_rows = intersection_df.loc[
            mismatch_mask, ["id", "image_path"]
        ].head(10)
        raise ValueError(
            "Intersection CSV contains image_path/id mismatches, e.g. "
            f"{mismatch_rows.to_dict(orient='records')}"
        )

    intersection_df = intersection_df.rename(
        columns={
            "timeofday": "time_of_day",
            "image_path": "metadata_image_path",
        }
    )
    return intersection_df


def attach_intersection_metadata(
    test_df: pd.DataFrame,
    intersection_df: pd.DataFrame,
) -> pd.DataFrame:
    """Attach intersection weather/time-of-day metadata to held-out test rows.

    The original evaluators derive their test set from the BDD100k 10K training
    images. The intersection CSV covers only the subset of 10K images that also
    has matching 100K metadata, so an inner join is intentional here.

    Steps
    -----
    1. Derive the BDD image ID from each held-out JPEG filename.
    2. Inner-join the held-out test set with the validated intersection metadata.
    3. Verify every matched row is a 10K training image and that both image
       basenames agree.
    4. Return only the matched rows needed for pair-wise evaluation.

    Parameters
    ----------
    test_df : pd.DataFrame
        Held-out segmentation rows containing ``image_paths`` and ``mask_paths``.
    intersection_df : pd.DataFrame
        Validated 10K/100K intersection metadata keyed by ``id``.

    Returns
    -------
    pd.DataFrame
        Matched held-out rows augmented with ``id``, ``weather``, and
        ``time_of_day``.

    Raises
    ------
    ValueError
        If no held-out images are present in the intersection, a matched row is
        not from the 10K training split, or image basenames disagree.
    """
    held_out_df = test_df.copy()
    held_out_df["id"] = held_out_df["image_paths"].map(
        lambda image_path: os.path.splitext(os.path.basename(image_path))[0]
    )

    # Unmatched held-out images are intentionally excluded: by construction the
    # pair CSV describes only images in the 10K/100K metadata intersection.
    matched_df = held_out_df.merge(
        intersection_df,
        on="id",
        how="inner",
        validate="one_to_one",
    )
    if matched_df.empty:
        raise ValueError(
            "No held-out segmentation images were found in the intersection CSV."
        )

    wrong_split_mask = matched_df["image_split"] != "train"
    if wrong_split_mask.any():
        wrong_rows = matched_df.loc[
            wrong_split_mask, ["id", "image_split"]
        ].head(10)
        raise ValueError(
            "Held-out evaluation rows must come from the 10K training split, "
            f"but the intersection CSV disagrees for: {wrong_rows.to_dict(orient='records')}"
        )

    test_basenames = matched_df["image_paths"].map(os.path.basename)
    metadata_basenames = matched_df["metadata_image_path"].map(os.path.basename)
    basename_mismatch = test_basenames != metadata_basenames
    if basename_mismatch.any():
        mismatch_rows = matched_df.loc[
            basename_mismatch, ["id", "image_paths", "metadata_image_path"]
        ].head(10)
        raise ValueError(
            "Held-out image paths do not match the intersection image paths, e.g. "
            f"{mismatch_rows.to_dict(orient='records')}"
        )

    return matched_df[
        ["image_paths", "mask_paths", "id", "weather", "time_of_day"]
    ].reset_index(drop=True)


def build_pair_test_frames(
    annotated_test_df: pd.DataFrame,
    pair_df: pd.DataFrame,
) -> List[Tuple[str, str, int, int, pd.DataFrame]]:
    """Build and validate one held-out DataFrame per evaluation condition pair.

    Steps
    -----
    1. Remove rows whose weather or time of day is ``undefined`` because the
       analyzer excludes those rows before writing the pair CSV.
    2. Count every observed pair in the held-out evaluation population.
    3. Require the pair CSV to contain exactly the same pairs with exactly the
       same counts.
    4. Build one segmentation DataFrame per validated pair.

    Parameters
    ----------
    annotated_test_df : pd.DataFrame
        Held-out rows matched to the 10K/100K intersection metadata.
    pair_df : pd.DataFrame
        Validated pair specification generated from this same held-out
        evaluation population.

    Returns
    -------
    List[Tuple[str, str, int, int, pd.DataFrame]]
        Tuples of weather, time of day, pair-CSV count, evaluation count, and
        matching segmentation sample rows. The two counts are guaranteed equal.

    Raises
    ------
    ValueError
        If no defined evaluation rows exist, pair sets differ, or any pair CSV
        count differs from the number of held-out samples actually evaluated.
    """
    # The analyzer excludes undefined environment labels before counting pairs,
    # so validation must use the identical population here.
    evaluable_df = annotated_test_df.loc[
        (annotated_test_df["weather"] != "undefined")
        & (annotated_test_df["time_of_day"] != "undefined")
    ].copy()
    if evaluable_df.empty:
        raise ValueError(
            "No held-out metadata rows have defined weather and time_of_day values."
        )

    # Build maps for both inputs so missing, extra, and count-mismatched pairs
    # all fail before expensive PGD computation begins.
    actual_counts = (
        evaluable_df.groupby(["weather", "time_of_day"], sort=False)
        .size()
        .to_dict()
    )
    expected_counts = {
        (str(row["weather"]), str(row["time_of_day"])): int(row["count"])
        for _, row in pair_df.iterrows()
    }

    actual_keys = set(actual_counts)
    expected_keys = set(expected_counts)
    missing_pairs = sorted(actual_keys - expected_keys)
    extra_pairs = sorted(expected_keys - actual_keys)
    mismatches: List[str] = []
    for pair_key in sorted(actual_keys & expected_keys):
        actual_count = int(actual_counts[pair_key])
        expected_count = expected_counts[pair_key]
        if actual_count != expected_count:
            mismatches.append(
                f"{pair_key[0]}/{pair_key[1]}: pair CSV={expected_count}, "
                f"evaluation={actual_count}"
            )

    if missing_pairs or extra_pairs or mismatches:
        details: List[str] = []
        if missing_pairs:
            details.append(
                "missing from pair CSV: "
                + ", ".join(f"{weather}/{time_of_day}" for weather, time_of_day in missing_pairs)
            )
        if extra_pairs:
            details.append(
                "not present in evaluation subset: "
                + ", ".join(f"{weather}/{time_of_day}" for weather, time_of_day in extra_pairs)
            )
        if mismatches:
            details.append("count mismatches: " + "; ".join(mismatches))
        raise ValueError(
            "Pair CSV does not match the held-out evaluation population: "
            + " | ".join(details)
            + ". Regenerate ./data/weather_timeofday_pair_data.csv with "
            "analyze_100k_10k_intersection.py."
        )

    pair_frames: List[Tuple[str, str, int, int, pd.DataFrame]] = []

    for _, pair_row in pair_df.iterrows():
        weather = str(pair_row["weather"])
        time_of_day = str(pair_row["time_of_day"])
        pair_csv_count = int(pair_row["count"])

        # Exact matching avoids inventing aliases between environmental categories.
        pair_mask = (
            (evaluable_df["weather"] == weather)
            & (evaluable_df["time_of_day"] == time_of_day)
        )
        subset_df = evaluable_df.loc[
            pair_mask, ["image_paths", "mask_paths"]
        ].reset_index(drop=True)
        evaluation_count = len(subset_df)

        # Equality was validated above; keeping both values in the output makes
        # the data provenance explicit without allowing them to diverge silently.
        pair_frames.append(
            (
                weather,
                time_of_day,
                pair_csv_count,
                evaluation_count,
                subset_df,
            )
        )

    if not pair_frames:
        raise ValueError(
            "No weather/time_of_day pairs are available for held-out evaluation."
        )

    return pair_frames


def flatten_robustness_metrics(
    weather: str,
    time_of_day: str,
    source_count: int,
    evaluation_count: int,
    metrics: Dict[str, Union[float, List[float]]],
) -> Dict[str, str | int | float]:
    """Flatten one pair's clean/adversarial robustness metrics for CSV export.

    Steps
    -----
    1. Store pair labels, pair-CSV count, evaluation count, and scalar robustness metrics.
    2. Expand clean and adversarial per-class IoUs into named columns.
    3. Add per-class relative IoU degradation for direct comparison.

    Parameters
    ----------
    weather : str
        Weather category for the evaluated subset.
    time_of_day : str
        Time-of-day category for the evaluated subset.
    source_count : int
        Count recorded in the pair CSV for this held-out evaluation pair.
    evaluation_count : int
        Number of held-out segmentation images actually evaluated for the pair;
        guaranteed to equal ``source_count``.
    metrics : Dict[str, Union[float, List[float]]]
        Robustness metrics returned by :func:`evaluate_robustness`.

    Returns
    -------
    Dict[str, str | int | float]
        Flat row ready for DataFrame/CSV export.
    """
    row: Dict[str, str | int | float] = {
        "weather": weather,
        "time_of_day": time_of_day,
        "pair_csv_count": source_count,
        "evaluation_count": evaluation_count,
        "clean_mean_iou": cast(float, metrics["clean_mean_iou"]),
        "adv_mean_iou": cast(float, metrics["adv_mean_iou"]),
        "untargeted_asr": cast(float, metrics["untargeted_asr"]),
        "clean_pixel_accuracy": cast(float, metrics["clean_pixel_accuracy"]),
        "adv_pixel_accuracy": cast(float, metrics["adv_pixel_accuracy"]),
        "clean_dice": cast(float, metrics["clean_dice"]),
        "adv_dice": cast(float, metrics["adv_dice"]),
        "clean_batch_macro_iou": cast(float, metrics["clean_batch_macro_iou"]),
        "adv_batch_macro_iou": cast(float, metrics["adv_batch_macro_iou"]),
    }

    clean_class_iou = cast(List[float], metrics["clean_class_iou"])
    adv_class_iou = cast(List[float], metrics["adv_class_iou"])
    for class_id in range(Configuration.NUM_VALID_CLASSES):
        class_slug = CLASS_NAMES[class_id].replace(" ", "_")
        clean_value = clean_class_iou[class_id]
        adv_value = adv_class_iou[class_id]
        degradation = (
            ((clean_value - adv_value) / clean_value) * 100.0
            if clean_value > 0.0
            else 0.0
        )
        row[f"clean_class_iou_{class_id}_{class_slug}"] = clean_value
        row[f"adv_class_iou_{class_id}_{class_slug}"] = adv_value
        row[f"class_iou_degradation_pct_{class_id}_{class_slug}"] = degradation

    return row


def parse_checkpoint_spec(value: str) -> Tuple[str, str]:
    """Parse a ``CHECKPOINT_NAME=CHECKPOINT_PATH`` command-line value.

    The checkpoint name is used as the result-directory name, while the path is
    passed unchanged to the model loader. Keeping both values in one argument
    makes the output location deterministic for every evaluated checkpoint.

    Steps
    -----
    1. Split the input on the first ``=`` so checkpoint paths may still contain
       additional ``=`` characters.
    2. Require both a non-empty checkpoint name and checkpoint path.
    3. Reject path separators in the checkpoint name because it must represent
       exactly one directory component under ``./model/weather_timeofday_pair``.
    4. Return the validated ``(checkpoint_name, checkpoint_path)`` pair.

    Parameters
    ----------
    value : str
        Raw ``--checkpoint`` value in ``CHECKPOINT_NAME=CHECKPOINT_PATH`` form.

    Returns
    -------
    Tuple[str, str]
        Validated checkpoint name and checkpoint path.

    Raises
    ------
    argparse.ArgumentTypeError
        If the value is not in ``NAME=PATH`` form, either side is empty, or the
        checkpoint name contains a path separator.
    """
    checkpoint_name, separator, checkpoint_path = value.partition("=")
    checkpoint_name = checkpoint_name.strip()
    checkpoint_path = checkpoint_path.strip()

    if separator == "" or not checkpoint_name or not checkpoint_path:
        raise argparse.ArgumentTypeError(
            "--checkpoint must use CHECKPOINT_NAME=CHECKPOINT_PATH, for example "
            "student_V5=./model/student_V5.pt."
        )

    # The name becomes one directory directly beneath the shared result root;
    # rejecting separators prevents it from escaping or nesting that directory.
    if (
        checkpoint_name in {".", ".."}
        or "/" in checkpoint_name
        or "\\" in checkpoint_name
    ):
        raise argparse.ArgumentTypeError(
            "Checkpoint name must be a single directory name without path separators."
        )

    return checkpoint_name, checkpoint_path


def parse_arguments() -> argparse.Namespace:
    """Parse command-line arguments for pair-wise PGD robustness evaluation.

    Steps
    -----
    1. Require the model checkpoint name and path in ``NAME=PATH`` form.
    2. Default the pair specification and 10K/100K intersection CSVs to their
       project ``./data`` locations while allowing explicit overrides.
    3. Add PGD, DataLoader, output, and visualization controls.
    4. Parse and return the argument namespace.

    Returns
    -------
    argparse.Namespace
        Parsed CLI arguments.
    """
    parser = argparse.ArgumentParser(
        description=(
            "Evaluate clean and PGD-adversarial segmentation robustness for "
            "each weather/time-of-day pair in the BDD100k 10K/100K metadata "
            "intersection."
        )
    )
    parser.add_argument(
        "--checkpoint",
        type=parse_checkpoint_spec,
        required=True,
        metavar="NAME=PATH",
        help=(
            "Checkpoint name and trained model checkpoint path, for example "
            "student_V5=./model/student_V5.pt."
        ),
    )
    parser.add_argument(
        "--pair-csv",
        type=str,
        default=ImagePath.WEATHER_TIMEOFDAY_PAIR_CSV,
        help=(
            "Pair/count CSV. Defaults to "
            "./data/weather_timeofday_pair_data.csv."
        ),
    )
    parser.add_argument(
        "--intersection-csv",
        type=str,
        default=ImagePath.METADATA_INTERSECTION_CSV,
        help=(
            "10K image / 100K metadata intersection CSV. Defaults to "
            "./data/bdd100k_10k_images_with_100k_metadata_intersection.csv."
        ),
    )
    parser.add_argument(
        "--epsilon",
        type=float,
        default=0.03,
        help="Maximum L-infinity perturbation radius. Defaults to 0.03.",
    )
    parser.add_argument(
        "--alpha",
        type=float,
        default=0.01,
        help="Step size per PGD iteration. Defaults to 0.01.",
    )
    parser.add_argument(
        "--steps",
        type=int,
        default=10,
        help="Number of PGD iterations. Defaults to 10.",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=Configuration.BATCH_SIZE,
        help="DataLoader batch size. Defaults to the configuration value.",
    )
    parser.add_argument(
        "--output-csv",
        type=str,
        default="robustness_weather_timeofday.csv",
        help=(
            "CSV filename for pair-wise clean/adversarial metrics. It is always "
            "saved inside the checkpoint-specific weather/time-of-day result directory."
        ),
    )
    parser.add_argument(
        "--visualize",
        action="store_true",
        default=True,
        help="Export adversarial visualizations from the union of positive-count pairs.",
    )
    return parser.parse_args()


def main() -> None:
    """Evaluate PGD robustness for each requested weather/time-of-day pair.

    Steps
    -----
    1. Load the pair specification and 10K/100K intersection metadata.
    2. Reconstruct the held-out segmentation split used by the base evaluator
       and keep only rows present in the metadata intersection.
    3. Validate that every pair CSV count exactly matches the corresponding
       held-out evaluation count.
    4. Resolve the checkpoint-specific result directory from ``--checkpoint``.
    5. Load and freeze the trained checkpoint only after data validation succeeds.
    6. Evaluate clean and PGD-adversarial metrics for each pair.
    7. Print and export the equal pair/evaluation counts and all metrics.
    8. Optionally visualize clean/adversarial predictions from evaluated pairs.

    Raises
    ------
    ValueError
        If attack/DataLoader arguments are invalid or input mapping fails.
    """
    args = parse_arguments()
    if args.batch_size <= 0:
        raise ValueError("--batch-size must be greater than zero.")
    if args.steps <= 0:
        raise ValueError("--steps must be greater than zero.")
    if args.epsilon < 0.0:
        raise ValueError("--epsilon must be non-negative.")
    if args.alpha <= 0.0:
        raise ValueError("--alpha must be greater than zero.")

    print("\n" + "=" * 76)
    print("ROBUSTNESS BY WEATHER / TIME OF DAY")
    print("=" * 76)

    # Load both CSV inputs before model work; pair counts are validated only
    # after reconstructing the exact held-out segmentation population they describe.
    pair_df = load_pair_specification(args.pair_csv)
    intersection_df = load_intersection_metadata(args.intersection_csv)

    print("Loading BDD100k held-out test split...")
    _, _, test_df = load_dataset_from_files()
    annotated_test_df = attach_intersection_metadata(test_df, intersection_df)
    print(
        f"Matched {len(annotated_test_df)} of {len(test_df)} held-out images "
        "to the 10K/100K metadata intersection."
    )

    pair_frames = build_pair_test_frames(annotated_test_df, pair_df)
    print(
        "Validated pair CSV counts against the held-out evaluation population; "
        "pair_csv_count == evaluation_count for every pair."
    )
    print(
        f"Built {len(pair_frames)} evaluable pairs covering "
        f"{sum(pair[3] for pair in pair_frames)} held-out segmentation images."
    )

    checkpoint_name, checkpoint_path = args.checkpoint

    # Every artifact for one checkpoint belongs to the same directory so
    # repeated evaluations cannot mix results from differently named models.
    output_directory = os.path.join(
        "./model",
        "weather_timeofday_pair",
        checkpoint_name,
    )
    os.makedirs(output_directory, exist_ok=True)

    print(f"Checkpoint name: {checkpoint_name}")
    print(f"Loading checkpoint from: {checkpoint_path}")
    model = load_trained_model(checkpoint_path, Configuration.DEVICE)
    print(f"Target execution device: {Configuration.DEVICE}")
    print(
        f"PGD configuration: steps={args.steps}, epsilon={args.epsilon}, "
        f"alpha={args.alpha}"
    )

    inference_transforms = A.Compose([
        A.Resize(height=Configuration.IMAGE_HEIGHT, width=Configuration.IMAGE_WIDTH),
        ToTensorV2(),
    ])

    summary_rows: List[Dict[str, str | int | float]] = []
    evaluated_frames: List[pd.DataFrame] = []
    for weather, time_of_day, source_count, sample_count, pair_test_df in pair_frames:
        print("\n" + "-" * 76)
        print(
            f"Pair: weather={weather!r}, time_of_day={time_of_day!r}, "
            f"pair_csv_count={source_count}, evaluation_count={sample_count}"
        )

        # A dedicated loader keeps both clean and adversarial confusion counts
        # scoped to one environmental pair at a time.
        pair_dataset = BDDSegmentationDataset(
            pair_test_df,
            transform=inference_transforms,
        )
        pair_loader = DataLoader(
            dataset=pair_dataset,
            batch_size=args.batch_size,
            shuffle=False,
            num_workers=Configuration.NUM_WORKERS,
        )
        results = evaluate_robustness(
            model=model,
            dataloader=pair_loader,
            device=Configuration.DEVICE,
            epsilon=args.epsilon,
            alpha=args.alpha,
            num_steps=args.steps,
        )
        summary_rows.append(
            flatten_robustness_metrics(
                weather,
                time_of_day,
                source_count,
                sample_count,
                results,
            )
        )
        evaluated_frames.append(pair_test_df)

        clean_iou = cast(float, results["clean_mean_iou"])
        adv_iou = cast(float, results["adv_mean_iou"])
        asr = cast(float, results["untargeted_asr"])
        print(f"  Clean Mean IoU       : {clean_iou:.4f}")
        print(f"  Adversarial Mean IoU : {adv_iou:.4f}")
        print(f"  Untargeted ASR       : {asr:.4f} ({asr * 100.0:.2f}%)")
        print(
            f"  Clean Pixel Accuracy : "
            f"{cast(float, results['clean_pixel_accuracy']):.4f}"
        )
        print(
            f"  Adv Pixel Accuracy   : "
            f"{cast(float, results['adv_pixel_accuracy']):.4f}"
        )
        print(
            f"  Clean Macro Dice     : "
            f"{cast(float, results['clean_dice']):.4f}"
        )
        print(
            f"  Adv Macro Dice       : "
            f"{cast(float, results['adv_dice']):.4f}"
        )

    # Preserve all class-wise values in the checkpoint-specific directory so no
    # robustness detail is mixed between differently named models.
    output_csv_path = os.path.join(output_directory, os.path.basename(args.output_csv))
    pd.DataFrame(summary_rows).to_csv(output_csv_path, index=False)
    print("\n" + "=" * 76)
    print(f"Saved pair-wise robustness metrics to: {output_csv_path}")

    if args.visualize:
        combined_test_df = pd.concat(evaluated_frames, ignore_index=True)
        output_path = os.path.join(
            output_directory,
            "adversarial_predictions_weather_timeofday.png",
        )
        print(f"Exporting adversarial sample predictions to {output_path}...")
        visualize_adversarial_predictions(
            model=model,
            test_df=combined_test_df,
            device=Configuration.DEVICE,
            epsilon=args.epsilon,
            alpha=args.alpha,
            num_steps=args.steps,
            output_path=output_path,
        )


if __name__ == "__main__":
    main()
